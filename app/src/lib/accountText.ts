const TEXT = { en, fr };

/** Textes du compte dans la langue de l'app ; en anglais, le message du serveur s'affiche tel quel. */
export function useAccountText() {
  const { lang } = useStore();
  const at = useCallback(
    (key: AccountKey, vars?: Record<string, string | number>) =>
      TEXT[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => (vars && k in vars ? String(vars[k]) : m)),
    [lang],
  );
  const errorText = useCallback(
    (e: AccountError) => {
      if (lang === "en" && e.message) return e.message;
      const key = `err.${e.code}` as AccountKey;
      return key in en ? at(key) : (e.message ?? at("err.server_error"));
    },
    [lang, at],
  );
  return { at, errorText, lang };
}
