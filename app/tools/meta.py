"""Catalogue Rago Hub : modules, sections et réglages, reliés aux labels du .bat legacy.

Chaque réglage pointe vers un label du .bat (nom@ligne). Les scripts sont extraits par
extract_bat.py ; ce fichier ne porte que ce que l'interface affiche (noms, explications,
risques) et l'organisation en modules.

risk   : "safe" (Sûr) ou "advanced" (Avancé : touche à la sécurité, au boot, ou supprime quelque chose)
reboot : un redémarrage est nécessaire pour que le réglage prenne effet
kind   : "tweak" (sélectionnable puis appliqué en lot) ou "action" (bouton, s'exécute tout de suite)
"""


def T(id, src, fr, en, dfr, den, risk='safe', reboot=True, kind='tweak', variants=None,
      requires=None, confirm=None, default_variant=None, native=None):
    return dict(id=id, src=src, name=dict(fr=fr, en=en), desc=dict(fr=dfr, en=den), risk=risk,
                reboot=reboot, kind=kind, variants=variants, requires=requires or [],
                confirm=confirm, defaultVariant=default_variant, native=native)


def V(id, src, fr, en=None, auto=None):
    return dict(id=id, src=src, label=dict(fr=fr, en=en or fr), auto=auto)


def REF(id):
    return dict(ref=id)


