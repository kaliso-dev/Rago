const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const b = await chromium.launch();
  const res = [];
  const ok = (c, m) => res.push((c ? 'OK  ' : 'FAIL') + ' ' + m);
  const page = async (extra = {}, nolic = false) => {
    const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
    p.on('pageerror', e => res.push('PAGEERR ' + e.message));
    const ls = { ...JSON.parse(fs.readFileSync(__dirname + '/ls-mouse.json', 'utf8')), 'rago.selection': [], 'rago.pendingUndo': [], ...extra };
    if (nolic) delete ls['rago.demoLicense'];
    await p.addInitScript((ls) => { if (sessionStorage.getItem('x')) return; sessionStorage.setItem('x', '1'); localStorage.clear(); for (const [k, v] of Object.entries(ls)) localStorage.setItem(k, typeof v === 'string' ? v : JSON.stringify(v)); }, ls);
    await p.goto('http://localhost:1420/', { waitUntil: 'networkidle' }); await p.waitForTimeout(2600);
    return p;
  };
  // recherche
  let p = await page();
  await p.keyboard.press('Control+k'); await p.waitForTimeout(400);
  ok(await p.locator('.w5 .pal[role=dialog]').count() === 1, 'Ctrl+K ouvre la recherche');
  ok(await p.evaluate(() => document.activeElement?.classList.contains('q')), 'la saisie a le focus');
  await p.keyboard.type('priority'); await p.waitForTimeout(200);
  const n = await p.locator('.pls2 li').count(); ok(n > 3, `résultats (${n})`);
  ok(await p.locator('.pls2 li.act').count() === 1 && await p.locator('.pls2 li').first().getAttribute('class') === 'act', 'premier résultat actif');
  await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown');
  ok(await p.locator('.pls2 li').nth(2).getAttribute('class') === 'act', 'flèches');
  ok(await p.locator('.pls2 li').nth(2).locator('svg.ent, .ent svg, svg').count() > 0, 'icône Entrée sur la ligne active');
  const tg = p.locator('.pls2 li').nth(3).locator('button.tg2');
  const was = (await tg.getAttribute('class')).includes('on');
  await tg.click(); await p.waitForTimeout(200);
  ok((await tg.getAttribute('class')).includes('on') !== was, '+ / ✓ change la sélection');
  ok(await p.locator('.w5 .pal').count() === 1, 'la recherche reste ouverte après +');
  await p.keyboard.press('Enter'); await p.waitForTimeout(700);
  ok(await p.locator('.w5 .pal').count() === 0, 'Entrée ferme et ouvre le module');
  await p.keyboard.press('Control+k'); await p.waitForTimeout(300); await p.keyboard.type('zzzzqq'); await p.waitForTimeout(200);
  ok(await p.locator('.pls2 li.emp').count() === 1, 'aucun résultat : message');
  await p.keyboard.press('Escape'); await p.waitForTimeout(400);
  ok(await p.locator('.w5 .pal').count() === 0, 'Échap ferme');
  await p.close();
  // invitation
  const due = { 'rago.reviewPrompt2': { usedMs: 1e9, nextAtMs: 0, snoozeUntil: 0, dismissals: 0, done: false, reviewed: false } };
  p = await page(due);
  ok(await p.locator('.rvp').count() === 1, 'invitation visible');
  const box = await p.locator('.rvp').boundingBox(); ok(Math.round(1440 - box.x - box.width) === 28 && Math.round(900 - box.y - box.height) === 28, 'invitation à 28 px du coin');
  ok(await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--rvp-h')) !== '', '--rvp-h posé');
  await p.mouse.click(700, 450); await p.waitForTimeout(200);
  ok(await p.locator('.rvp').count() === 1, 'clic sur la page passe à travers (pas bloqué)');
  await p.keyboard.press('Control+k'); await p.waitForTimeout(400);
  ok(await p.locator('.rvp').count() === 0, 'invitation cachée sous une fenêtre');
  await p.keyboard.press('Escape'); await p.waitForTimeout(500);
  await p.click('.rvp .btn.gh2'); await p.waitForTimeout(500);
  ok(await p.locator('.rvp').count() === 0, 'Plus tard la cache');
  await p.close();
  p = await page({ ...due, 'rago.selection': ['lat_directx'] });
  await p.evaluate(() => { const a = [...document.querySelectorAll('.side a')].find(x => /latency/i.test(x.textContent)); a.click(); }); await p.waitForTimeout(900);
  const b2 = await p.locator('.rvp').boundingBox(); ok(Math.round(900 - b2.y - b2.height) === 100, `barre Appliquer visible : invitation remontée (${Math.round(900 - b2.y - b2.height)})`);
  await p.close();
  // avis
  p = await page(due);
  await p.click('.rvp .btn.red'); await p.waitForTimeout(700);
  ok(await p.locator('.w5 .mdl.rv2').count() === 1, 'formulaire d\'avis (connecté par la licence)');
  await p.click('.w5 .mf .btn.red'); await p.waitForTimeout(400);
  ok(await p.locator('.w5 .rv2 .err2').count() === 1, 'envoi sans note : erreur');
  await p.locator('.st4.big button').nth(2).focus(); await p.keyboard.press('ArrowRight'); await p.waitForTimeout(100);
  ok(await p.locator('.st4.big button.on').count() >= 1, 'flèches : note');
  await p.locator('.st4.big button').nth(3).click();
  ok(await p.locator('.st4.big button.on').count() === 4, 'clic : 4 étoiles');
  await p.fill('.in3.ta textarea', 'Great app.'); ok((await p.textContent('.in3.ta small')).replace(/\s/g, '') === '10/600', 'compteur');
  await p.fill('.pnm input', 'Player');
  ok(await p.textContent('.pnm .av') === 'P', 'initiale du nom');
  await p.click('.w5 .mf .btn.red'); await p.waitForTimeout(1500);
  ok(await p.locator('.w5 .gate2 .okh').count() === 1, 'merci');
  ok(await p.locator('.rvq .st4 i.on').count() === 4, 'merci : 4 étoiles');
  await p.click('.w5 .mf .btn'); await p.waitForTimeout(500);
  ok(await p.locator('.w5 .mdl').count() === 0, 'fermer');
  ok(await p.locator('.rvp').count() === 0, 'plus d\'invitation après l\'avis');
  await p.close();
  p = await page(due, true);
  await p.click('.rvp .btn.red'); await p.waitForTimeout(700);
  ok(await p.locator('.w5 .gate2 #rv-email').count() === 1, 'connexion d\'abord (sans licence)');
  await p.click('.w5 .cta'); await p.waitForTimeout(200);
  ok(await p.evaluate(() => document.activeElement?.id) === 'rv-email', 'champ vide : focus');
  await p.fill('#rv-email', 'player@example.com'); await p.fill('#rv-password', 'ab'); await p.click('.w5 .cta'); await p.waitForTimeout(1500);
  ok(await p.locator('.w5 .err2').count() === 1, 'mauvais mot de passe : erreur');
  await p.fill('#rv-password', 'password123'); await p.click('.w5 .cta'); await p.waitForTimeout(1800);
  ok(await p.locator('.w5 .mdl.rv2').count() === 1, 'connecté : formulaire');
  await p.click('.w5 .mf .btn.gh2'); await p.waitForTimeout(500);
  ok(await p.locator('.w5 .mdl').count() === 0 && await p.locator('.rvp').count() === 0, 'annuler : fermé, compte comme Plus tard');
  await p.close();
  console.log(res.join('\n'));
  await b.close();
})();
