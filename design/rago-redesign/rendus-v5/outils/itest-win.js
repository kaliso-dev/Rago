// test d'interaction des fenêtres v5 : Échap, clic dehors, focus, cases à cocher, annulation du lot, résiliation
const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = [];
  p.on('pageerror', e => errs.push(e.message));
  p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  const ls = { ...JSON.parse(fs.readFileSync(__dirname + '/ls-mouse.json', 'utf8')), 'rago.selection': ['pri_game', 'pri_w32', 'pri_irq8', 'pri_policy'], 'rago.pendingUndo': [] };
  await p.addInitScript((ls) => { if (sessionStorage.getItem('x')) return; sessionStorage.setItem('x', '1'); localStorage.clear(); localStorage.setItem('rago.lang', '"en"'); for (const [k, v] of Object.entries(ls)) localStorage.setItem(k, typeof v === 'string' ? v : JSON.stringify(v)); }, ls);
  await p.goto('http://localhost:1420/', { waitUntil: 'networkidle' });
  await p.waitForTimeout(2600);
  const go = (re) => p.evaluate((re) => { const a = [...document.querySelectorAll('.side a')].find(x => new RegExp(re, 'i').test(x.textContent)); a && a.click(); }, re);
  const n = () => p.locator('.w5:not(.flt)').count();
  const ok = (c, m) => console.log((c ? 'OK  ' : 'FAIL') + ' ' + m);
  await go('^\\s*latency'); await p.waitForTimeout(700);
  await p.click('.win .ap .btn'); await p.waitForTimeout(500);
  ok(await n() === 1, 'apply window opens');
  ok(await p.evaluate(() => document.activeElement?.classList.contains('red')), 'focus on red button');
  const opt = p.locator('.w5 .opt[role=checkbox]').first();
  const before = await opt.getAttribute('aria-checked');
  await opt.focus(); await p.keyboard.press('Space'); await p.waitForTimeout(150);
  ok(await opt.getAttribute('aria-checked') !== before, 'space toggles restore option');
  await p.keyboard.press('Space'); await p.waitForTimeout(150);
  await p.keyboard.press('Escape'); await p.waitForTimeout(500);
  ok(await n() === 0, 'escape closes');
  await p.click('.win .ap .btn'); await p.waitForTimeout(500);
  await p.mouse.click(20, 880); await p.waitForTimeout(500);
  ok(await n() === 0, 'click outside closes');
  await p.click('.win .ap .btn'); await p.waitForTimeout(500);
  await p.click('.w5 .mdl'); await p.waitForTimeout(300);
  ok(await n() === 1, 'click inside keeps it');
  await p.click('.w5 .mf .btn.red'); await p.waitForTimeout(1200);
  ok(await p.locator('.runw').count() === 1, 'run screen shows');
  ok(await p.locator('.runw .ra .btn').count() === 1, 'stop button while running');
  await p.click('.runw .ra .btn'); await p.waitForSelector('.runw.fin', { timeout: 30000 });
  ok(/cancel|stopp/i.test(await p.locator('.runw .rst').innerText()), 'stopped title: ' + (await p.locator('.runw .rst').innerText()));
  await p.click('.runw .ra .btn:last-child'); await p.waitForTimeout(600);
  ok(await p.locator('.runw').count() === 0, 'close run screen');
  await go('settings'); await p.waitForTimeout(700);
  await p.locator('button').filter({ hasText: /cancel subscription/i }).first().click(); await p.waitForTimeout(500);
  const z = await p.evaluate(() => { const w = document.querySelector('.w5:not(.flt)'); return [w.parentElement === document.body, getComputedStyle(w).zIndex]; });
  ok(z[0], 'cancel window rendered in body, z ' + z[1]);
  ok(await p.evaluate(() => document.activeElement?.textContent.trim().toLowerCase()) === 'keep premium', 'focus on keep premium');
  await p.locator('.w5 .mf .btn').nth(1).click(); await p.waitForTimeout(1500);
  ok(/canceled/i.test(await p.locator('.w5 h2').innerText()), 'canceled step');
  await p.click('.w5 .mf .btn.red'); await p.waitForTimeout(500);
  ok(await n() === 0, 'close after cancel');
  ok(await p.locator('button').filter({ hasText: /resume subscription/i }).count() === 1, 'resume button shown');
  await p.locator('button').filter({ hasText: /sign out/i }).first().click(); await p.waitForTimeout(500);
  ok(await n() === 1 && await p.locator('.w5 .mf .btn').count() === 3, 'signout window, 3 buttons');
  await p.locator('.w5 .mf .btn.gh2').nth(1).click(); await p.waitForTimeout(500);
  ok(await n() === 0, 'signout cancel closes');
  console.log('errors:', errs.slice(0, 5).join(' | ') || 'none');
  await b.close();
})();
